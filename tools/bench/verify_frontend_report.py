def i_citations() -> None:
    ref_pat = re.compile(
        r"\b((?:ui/web_new_v2/)?(?:js|css/components|css)/[\w.\-]+\.(?:js|css)"
        r"|css/[\w\-]+\.css)\s*:\s*(\d+)")
    alias_pat = re.compile(r"`\b(components/[\w\-]+\.css|tokens\.css|themes\.css)\s*:\s*(\d+)")
    unresolved: list[str] = []
    bare: list[tuple[str, int]] = []
    targets: list[tuple[str, int]] = []
    seen: set[tuple[str, int]] = set()
    for m in ref_pat.finditer(doc):
        f = m.group(1)
        if not f.startswith("ui/web_new_v2/"):
            f = "ui/web_new_v2/" + f
        targets.append((f, int(m.group(2))))
    for m in alias_pat.finditer(doc):
        targets.append(("ui/web_new_v2/css/" + m.group(1), int(m.group(2))))
    for f, n in targets:
        if (f, n) in seen:
            continue
        seen.add((f, n))
        if not (REPO / f).exists():
            unresolved.append(f"{f} (missing file)")
        elif n > len(src(f)):
            unresolved.append(f"{f}:{n} out of range (file has {len(src(f))} lines)")
        elif not src(f)[n - 1].strip():
            unresolved.append(f"{f}:{n} is blank")
    # A citation that no longer resolves is real drift in the document, not a broken
    # verifier, so it is reported with its doc line rather than failed on: these files
    # are edited by other passes and the numbers in the report are dated snapshots.
    if unresolved:
        reports.append(f"report: {len(unresolved)} of {len(seen)} file:line citations no "
                       f"longer resolve to a real, non-blank line "
                       f"(line drift; the claim text is still checked by the "
                       f"content anchors): " + "; ".join(unresolved[:10]))
    else:
        oks.append(f"all {len(seen)} distinct file:line references in the report resolve "
                   f"to a real, non-blank line")

    # Bare `foo.css:123` citations are outside the grammar above (the report uses
    # them for shorthand).  They are resolved here and reported, not asserted: the
    # shorthand is not something the report promises to machine-check.
    css_names = {p.name: p for p in CSS.rglob("*.css")}
    for m in re.finditer(r"`?\b([\w\-]+\.css)\s*:\s*(\d+)", doc):
        name, n = m.group(1), int(m.group(2))
        p = css_names.get(name)
        if p is None or (name, n) in seen:
            continue
        seen.add((name, n))
        bare.append((name, n))
        got = line(str(p.relative_to(REPO)).replace("\\", "/"), n)
        if got is None:
            reports.append(f"bare citation {name}:{n} -> out of range "
                           f"(file has {len(src(str(p.relative_to(REPO)).replace(chr(92), '/')))} lines)")
        elif not got.strip():
            reports.append(f"bare citation {name}:{n} -> blank line "
                           f"(the shorthand citation has drifted)")
    reports.append(f"bare `name.css:line` citations inspected (reported, not asserted): "
                   f"{len(bare)} distinct")


