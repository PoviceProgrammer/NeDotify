def class_tokens(body: str) -> set[str]:
    """Class names that can appear in the live DOM: HTML class="" and JS
    className=/classList literals, including the HTML fragments built inside
    template literals (`class="..."`)."""
    out: set[str] = set()
    for m in re.finditer(r'class="([^"]*)"', body):
        out.update(m.group(1).split())
    for m in re.finditer(r"className\s*=\s*(['\"`])([^'\"`]*)\1", body):
        out.update(m.group(2).split())
    for m in re.finditer(r"classList\.(?:add|remove|toggle)\(\s*(['\"`])([^'\"`]*)\1", body):
        out.update(m.group(2).split())
    for m in re.finditer(r"class(?:Name)?\s*=\s*['\"]([a-z0-9 \-]+)['\"]", body):
        out.update(m.group(1).split())
    return {c for c in out if c}


