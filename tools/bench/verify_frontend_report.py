skips: list[str] = []


def check(name: str, cond: bool, detail: str = "") -> bool:
    (oks if cond else fails).append(f"{name}{(' :: ' + detail) if detail else ''}")
    return bool(cond)


def agree(name: str, token: str, value: object) -> bool:
    """The report must quote `token`, and the number inside it must equal `value`.

    The expected number is never written down here - it is read out of the
    artefact - so this check can only fail because the *document* is stale.
    """
    quoted = re.search(r"\d[\d \u00a0\u202f]*", token)
    ok = True
    if not check(f"report mentions {token!r}", token in doc):
        ok = False
    if quoted is not None and isinstance(value, (int, float)):
        said = int(re.sub(r"[\s\u00a0\u202f]", "", quoted.group(0)))
        if not check(f"report's {token!r} == artefact's {value!r}", said == value,
                     f"document says {said}, artefact holds {value}"):
            ok = False
    return ok


def report(label: str, live: object, recorded: object, regen: str) -> None:
    """Non-fatal snapshot line: a recorded measurement and how to refresh it."""
    verdict = "agrees" if live == recorded else "DIFFERS"
    reports.append(f"{label}: live={live!r} recorded={recorded!r} [{verdict}]"
                   f"  -> {regen}")


def skip(what: str, reason: str, regen: str = "") -> None:
    skips.append(f"{what}: {reason}" + (f"  -> {regen}" if regen else ""))


# ------------------------------------------------------------------ source access
_lines_cache: dict[str, list[str]] = {}
_text_cache: dict[str, str] = {}


def src(rel: str) -> list[str]:
    if rel not in _lines_cache:
        _lines_cache[rel] = (REPO / rel).read_text(encoding="utf-8").splitlines()
    return _lines_cache[rel]


def text(rel: str) -> str:
    if rel not in _text_cache:
        _text_cache[rel] = (REPO / rel).read_text(encoding="utf-8")
    return _text_cache[rel]


def line(rel: str, n: int) -> str | None:
    """1-based line, or None when the file is gone or the number is out of range."""
    try:
        lines = src(rel)
    except OSError as exc:
        check(f"{rel} is readable", False, str(exc))
        return None
    return lines[n - 1] if 0 < n <= len(lines) else None


def load(name: str, regen: str) -> dict | None:
    path = RES / name
    if not path.exists():
        skip(name, "artefact not found", regen)
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        skip(name, f"unreadable ({exc})", regen)
        return None


def records(art: dict | None, key: str = "declarations") -> list[dict]:
    if not art:
        return []
    raw = art.get(key)
    if not isinstance(raw, list):
        return []
    return [r for r in raw if isinstance(r, dict)]


def norm(line_text: str) -> str:
    return re.sub(r"\s+", " ", line_text).strip()

# a `${...}` interpolation hole inside a JS template literal
_HOLE_RE = re.compile(r"\$\{[^}]*\}")


