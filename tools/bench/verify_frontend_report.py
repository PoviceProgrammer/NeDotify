def e_code_claims() -> None:
    utils = text("ui/web_new_v2/js/utils.js")
    u_lines = utils.splitlines()

    # createTrackElement: brace-matched instead of a hardcoded line window
    try:
        start = next(i for i, l in enumerate(u_lines)
                     if "export function createTrackElement" in l)
    except StopIteration:
        check("createTrackElement exists in utils.js", False)
        return
    depth, seen, end = 0, False, start
    for i in range(start, len(u_lines)):
        depth += u_lines[i].count("{") - u_lines[i].count("}")
        if u_lines[i].count("{"):
            seen = True
        if seen and depth <= 0:
            end = i
            break
    body = "\n".join(u_lines[start:end + 1])
    n_listeners = body.count(".addEventListener(")
    agree("createTrackElement registers 7 listeners per row", "**7** listeners per row",
          n_listeners)
    check("createTrackElement is one function (brace matching found its end)",
          end > start, f"lines {start + 1}-{end + 1}")

    first_party = [p for p in sorted(JS.glob("*.js")) if not p.name.endswith(".min.js")]
    n_render = sum(len(re.findall(r"\brenderIcons\s*\(",
                                  p.read_text(encoding="utf-8"))) for p in first_party)
    agree("renderIcons call sites app-wide", "55 call sites", n_render)
