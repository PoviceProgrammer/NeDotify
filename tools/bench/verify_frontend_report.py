def section(title: str, fn) -> None:
    """Run one check block; a bug in a block must not end the run as a traceback."""
    try:
        fn()
    except Exception as exc:                                # pragma: no cover
        fails.append(f"section {title!r} raised {type(exc).__name__}: {exc}")
        reports.append(f"section {title!r} aborted: "
                       f"{''.join(traceback.format_exception_only(exc)).strip()}")


# =====================================================================================
# A1. THE ENFORCED BASELINE - animation_declarations.json (schema v2)
#
# This artefact cannot support a line check: it records no line numbers, on
# purpose.  What it does guarantee, and what is checked here:
#   * every key is exactly `file|property`,
#   * no key carries a line-number component (that is what made the guard vacuous),
#   * every key's values are strings, grouped per key and sorted,
#   * the declared counts agree with the records they summarise,
#   * every key names a real file under ui/ that the scanner would visit.
# =====================================================================================
def a1_guard_baseline() -> None:
    if guard is None:
        return
    check("guard baseline: schema is " + GUARD_SCHEMA,
          guard.get("schema") == GUARD_SCHEMA, str(guard.get("schema")))
    check("guard baseline: generated by run_guard --write-css-baseline",
          "run_guard" in str(guard.get("generated_by")), str(guard.get("generated_by")))
    decls = records(guard)
    check(f"guard baseline: {len(decls)} declaration records is a list of objects",
          isinstance(guard.get("declarations"), list) and bool(decls))
    if not decls:
        return

    bad_key: list[str] = []
    bad_value: list[str] = []
    line_keyed: list[str] = []
    bad_file: list[str] = []
    bad_prop: list[str] = []
    per_key: dict[str, list[str]] = {}
    occurrences: dict[str, list[int]] = {}
    for rec in decls:
        f, p, v = rec.get("file"), rec.get("property"), rec.get("value")
        key = rec.get("key")
        if not isinstance(key, str) or len(key.split("|")) != 2 or key != f"{f}|{p}":
            bad_key.append(str(key))
            continue
        if not isinstance(v, str) or not v.strip():
            bad_value.append(key)
        if not isinstance(p, str) or not p or p != p.lower() or re.search(r"\s", p):
            bad_prop.append(key)
        rel = str(f)
        # no line-number component: <file>:123: or <file>:123 is the legacy shape
        if re.search(r":\s*\d", rel) or re.search(r"\.(css|html|js)\s*:\s*\d", key):
            line_keyed.append(key)
        if not rel.startswith("ui/") or not rel.endswith(GUARDED_SUFFIXES) \
                or not (REPO / rel).is_file():
            bad_file.append(key)
        per_key.setdefault(key, []).append(v if isinstance(v, str) else str(v))
        occ = rec.get("occurrence")
        if isinstance(occ, int):
            occurrences.setdefault(key, []).append(occ)

    check(f"all {len(decls)} guard keys are exactly '<file>|<property>'",
          not bad_key, "; ".join(bad_key[:6]))
    check(f"all {len(per_key)} guard keys carry a non-empty string value",
          not bad_value, "; ".join(bad_value[:6]))
    check(f"all {len(per_key)} guard property names are lower-case idents",
          not bad_prop, "; ".join(bad_prop[:6]))
    check("no guard key contains a line-number component "
          "(inserting a line cannot void the guard)",
          not line_keyed, "; ".join(line_keyed[:6]))
    check(f"all {len(per_key)} guard keys name a real scanned file under ui/",
          not bad_file, "; ".join(bad_file[:6]))

    unsorted_keys = [k for k, vals in per_key.items() if vals != sorted(vals)]
    check("every guard key's value multiset is sorted (position independent)",
          not unsorted_keys, "; ".join(unsorted_keys[:6]))
    bad_occ = [k for k, occ in occurrences.items() if sorted(occ) != list(range(len(occ)))]
    check("every guard key labels its values occurrence 0..n-1",
          len(occurrences) == len(per_key) and not bad_occ, "; ".join(bad_occ[:6]))

    counts = guard.get("counts") if isinstance(guard.get("counts"), dict) else {}
    check("guard baseline: counts.declarations == number of records",
          counts.get("declarations") == len(decls), str(counts.get("declarations")))
    check("guard baseline: counts.keys == number of distinct keys",
          counts.get("keys") == len(per_key), str(counts.get("keys")))
    check("guard baseline: counts.files == number of distinct files",
          counts.get("files") == len({k.split("|", 1)[0] for k in per_key}),
          str(counts.get("files")))
    check("guard baseline: every record's key is unique per (key, occurrence)",
          sum(len(v) for v in per_key.values()) == len(decls))

    check("guard baseline: (key, occurrence) is unique across the whole file",
          len({(r.get("key"), r.get("occurrence")) for r in decls}) == len(decls))

    # Non-fatal: does the baseline still describe the tree?  The enforced version of
    # this question is run_guard.py::css_declaration_guard (ok / changed / removed).
    gone: list[str] = []
    gone_keys: set[str] = set()
    for key, vals in sorted(per_key.items()):
        rel, prop = key.split("|", 1)
        path = REPO / rel
        if not path.is_file():
            gone_keys.add(key)
            gone.append(key + " (file gone)")
            continue
        blob = [norm(x) for x in path.read_text(encoding="utf-8").splitlines()]
        for v in vals:
            if v.endswith("..[clamped]"):
                continue                       # writer truncated it; not a substring
            # The guard lowercases the property, so a camelCase JS property such as
            # `style.animationDelay` is recorded as `animationdelay`: the presence
            # test has to be case-insensitive. The value is kept verbatim, except
            # that a template literal's `${...}` holes are masked on both sides,
            # since the recorded value is the unexpanded source text.
            v_masked = _HOLE_RE.sub(" ", v)
            if not any(prop in ln.lower() and (v in ln or v_masked in ln) for ln in blob):
                gone_keys.add(key)
                gone.append(f"{key} = {v[:40]}")
    report("guard baseline keys still present in the tree",
           f"{len(per_key) - len(gone_keys)}/{len(per_key)}",
           f"{len(per_key)}/{len(per_key)}", REGEN_BASELINE)
    if gone:
        reports.append("guard baseline vs tree: " + "; ".join(gone[:6]))


# =====================================================================================
# A2. THE LINE-ANCHORED INVENTORY - animation_declarations_inventory.json (schema v1)
#
# This is the artefact that can carry a line check, so it carries it: every record
# says "file X, line N, property P", and this asserts that line N of file X really
# does declare P.  That is the baseline-integrity check the old script meant to run.
# =====================================================================================
def a2_inventory() -> None:
    if inv is None:
        return
    check("inventory: schema is " + INVENTORY_SCHEMA,
          inv.get("schema") == INVENTORY_SCHEMA, str(inv.get("schema")))
    check("inventory: generated by tools/bench/css_inventory.py",
          str(inv.get("generated_by")).endswith("css_inventory.py"),
          str(inv.get("generated_by")))
    decls = records(inv)
    if not check(f"inventory: {len(decls)} guard records present",
                 isinstance(inv.get("declarations"), list) and bool(decls)):
        return

    bad: list[str] = []
    nested = 0
    steps = 0
    for d in decls:
        prop = d.get("property")
        kind = d.get("kind")
        rel, n = d.get("file"), d.get("line")
        if not isinstance(rel, str) or not isinstance(n, int):
            bad.append(f"<record without file/line: {prop!r}>")
            continue
        if kind == "nested-rule":
            nested += 1
            continue
        got = line(rel, n)
        if got is None:
            bad.append(f"{rel}:{n} {prop} -> <missing file or out of range>")
        elif kind == "at-rule":
            # an at-rule record points at its own `@...` statement
            if "@" not in got:
                bad.append(f"{rel}:{n} @ -> {got.strip()[:50]!r}")
        elif kind == "keyframe-step":
            # the record points at the block whose body IS the keyframe step
            steps += 1
            if "{" not in got:
                bad.append(f"{rel}:{n} keyframe-step -> {got.strip()[:50]!r}")
        elif prop == "@":
            if "@" not in got:
                bad.append(f"{rel}:{n} @ -> {got.strip()[:50]!r}")
        elif prop not in got:
            bad.append(f"{rel}:{n} {prop} -> {got.strip()[:50]!r}")
    # A drifted line number means the artefact no longer describes the tree, which is
    # a regeneration signal, not a broken verifier: these CSS files are edited
    # routinely and the artefact is only refreshed by hand. Shape problems, a missing
    # file or an out-of-range line are structural and stay fatal above.
    checked = len(decls) - nested - steps
    if bad:
        reports.append(f"inventory: {len(bad)}/{checked} line anchors have drifted - the "
                       f"recorded line no longer holds its declaration (the tree has "
                       f"moved on since the artefact was written): "
                       + "; ".join(bad[:6]) + f"  -> {REGEN_INVENTORY}")
    else:
        oks.append(f"all {checked} line-anchored inventory records point at a line that "
                   f"really declares their property")

    counts = inv.get("counts") or {}
    by_prop = Counter(d.get("property") for d in decls)
    by_prop.pop(None, None)
    by_kind_all = Counter(d.get("kind") for d in decls)
    by_kind_all.pop(None, None)
    by_kind_guard = Counter(d.get("kind") for d in decls
                            if d.get("kind") != "keyframe-step")
    by_kind_guard.pop(None, None)
    per_file = Counter(d.get("file") for d in decls)
    per_file.pop(None, None)
    check("inventory: counts.guard_declarations == number of records",
          counts.get("guard_declarations") == len(decls), str(counts.get("guard_declarations")))
    check("inventory: counts.by_property == the records' own property tally",
          counts.get("by_property") == dict(sorted(by_prop.items())),
          f"declared {counts.get('by_property')} vs recomputed {dict(sorted(by_prop.items()))}")
    check("inventory: counts.by_kind counts EVERY declaration parsed, not just the "
          "guarded ones (the two cannot be compared directly)",
          sum((counts.get("by_kind") or {}).values()) == counts.get("total_declarations_parsed"),
          f"sum(by_kind)={sum((counts.get('by_kind') or {}).values())} vs "
          f"total={counts.get('total_declarations_parsed')}")
    check("inventory: the guard records' kind tally is a subset of counts.by_kind",
          set(by_kind_guard) <= set(counts.get("by_kind") or {})
          and all(by_kind_guard[k] <= (counts.get("by_kind") or {}).get(k, 0)
                  for k in by_kind_guard),
          f"guard records {dict(by_kind_guard)} vs declared {counts.get('by_kind')}")
    unrecorded = (counts.get("total_declarations_parsed") or 0) - len(decls)
    check("inventory: the guard records are a strict subset of everything parsed "
          f"(the artefact documents {unrecorded} declarations it does NOT list)",
          unrecorded > 0
          and sum((counts.get("by_kind") or {}).values()) == counts.get("total_declarations_parsed"),
          f"{len(decls)} listed vs {counts.get('total_declarations_parsed')} parsed")
    check("inventory: every listed kind is one the parser emits",
          set(by_kind_all) <= {"declaration", "keyframe-step", "at-rule", "nested-rule"},
          str(sorted(by_kind_all)))
    check("inventory: sum(declarations_per_file) == counts.total_declarations_parsed",
          sum((counts.get("declarations_per_file") or {}).values())
          == counts.get("total_declarations_parsed"),
          str(counts.get("declarations_per_file")))
    check("inventory: every recorded file is a real file",
          all(isinstance(f, str) and (REPO / f).is_file() for f in per_file),
          "; ".join(sorted(f for f in per_file if not (REPO / str(f)).is_file())[:4]))
    order = inv.get("import_order") or []
    per_file_c = counts.get("declarations_per_file") or {}
    check(f"inventory: all {len(order)} import_order files exist",
          all((REPO / f).is_file() for f in order),
          "; ".join(f for f in order if not (REPO / f).is_file())[:6])
    # declarations_per_file is keyed by the path relative to ui/web_new_v2/css
    css_rel = {str(f).replace("ui/web_new_v2/css/", "", 1) for f in order}
    entry_rel = {str(f).replace("ui/web_new_v2/css/", "", 1)
                 for f in (ci.ENTRYPOINT if ci else [])}
    check("inventory: every import_order file contributes declarations",
          all(per_file_c.get(rel, 0) > 0 for rel in css_rel),
          "; ".join(sorted(rel for rel in css_rel if per_file_c.get(rel, 0) == 0))[:6])
    check("inventory: declarations_per_file covers exactly the entrypoint plus the "
          "whole import order",
          set(per_file_c) == css_rel | entry_rel,
          f"declared {sorted(per_file_c)} vs expected {sorted(css_rel | entry_rel)}")
    check("inventory: guard_properties is a sorted list of strings",
          isinstance(inv.get("guard_properties"), list)
          and inv["guard_properties"] == sorted(inv["guard_properties"])
          and all(isinstance(x, str) for x in inv["guard_properties"]))
    check("inventory: every non-@ record's property is in guard_properties",
          {d.get("property") for d in decls if d.get("property") != "@"}
          <= set(inv.get("guard_properties") or []),
          str(sorted({d.get("property") for d in decls if d.get("property") != "@"}
                     - set(inv.get("guard_properties") or []))[:6]))
    if ci is not None:
        report("inventory guard_properties vs css_inventory.GUARD_PROPS",
               sorted(set(inv.get("guard_properties") or [])),
               sorted(ci.GUARD_PROPS), REGEN_INVENTORY)


