"""Verify the numeric / line-reference claims made in docs/perf/prof_frontend.md
against the artefacts in tools/bench/results/ and against the sources.
READ-ONLY.  Exits non-zero when a structural check fails.  Never raises.

    .venv_win\\Scripts\\python.exe tools/bench/verify_frontend_report.py

Standalone: deliberately NOT collected by pytest (`pytest.ini` sets
`testpaths = tests`).

--------------------------------------------------------------------------------------
THREE TIERS OF CHECK - and why the difference matters
--------------------------------------------------------------------------------------

CHECK()  A structural invariant: true or false by construction.  A schema string,
         a key shape, a count that has to agree with the records stored next to
         it, a declaration that has to be at the line the artefact says it is at,
         a string the document quotes.  Failure => non-zero exit.

AGREE()  The document must quote a number that the *recorded artefact* it cites
         also holds.  The number is parsed out of the document text and compared
         with the value read out of the artefact at run time, so **no measurement
         is ever written down twice in this file**.  The verifier therefore cannot
         disagree with the tree - it can only disagree with a stale document,
         which is the only thing a verifier of a document should be able to fail
         on.  Failure => non-zero exit.

REPORT() A recorded measurement that may legitimately be out of date.  Every
         artefact here is regenerated by hand and the tree can be mid-edit while
         the perf pass runs, so artefact-vs-tree drift is *reported* with the
         command that refreshes it instead of failing the run: an assertion
         pinned to a number another agent's in-flight edit can move is worse
         than no assertion, because it cries wolf forever.  The ENFORCED
         counterpart of the CSS one is
         `tools/visual_guard/run_guard.py::css_declaration_guard`; this script
         deliberately does not duplicate enforcement.

A missing or unparsable artefact is a SKIP with a reason, never a crash, and
every check that depends on it is skipped with it.

--------------------------------------------------------------------------------------
THE TWO CSS ARTEFACTS ARE NOT INTERCHANGEABLE
--------------------------------------------------------------------------------------

tools/bench/results/animation_declarations.json
    The *enforced* visual-guard baseline, schema
    `nedotify.animation-declarations.v2`, written by
    `run_guard.py --write-css-baseline`.  Keys are `file.css|property` with the
    normalised values in a list under the key and **no line numbers anywhere** -
    that is deliberate: line-numbered keys made the guard's key-intersection
    structurally empty, so it passed vacuously.  It can therefore support shape /
    self-consistency / presence checks only, never "is the property on line N".

tools/bench/results/animation_declarations_inventory.json
    The line-accurate *reporting* artefact, schema
    `nedotify.animation-declarations.v1`, written by `css_inventory.py`.  Every
    record really does carry `file` and `line`, so this is where the
    "the recorded line in the recorded file really contains that property"
    check belongs.

Section A below is split accordingly.  The two files must never be merged again:
writing the line-numbered report to the guard's path is exactly what used to make
the guard vacuous.
"""
