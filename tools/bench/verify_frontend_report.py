def a3_blur_map() -> None:
    if blur is None:
        return
    decls = records(blur)
    check("blur map: schema is nedotify.css-blur-map.v1",
          blur.get("schema") == "nedotify.css-blur-map.v1", str(blur.get("schema")))
    if not check(f"blur map: {len(decls)} records present",
                 isinstance(blur.get("declarations"), list) and bool(decls)):
        return
    bad: list[str] = []
    drifted: list[str] = []
    for d in decls:
        rel, n, prop = d.get("file"), d.get("line"), d.get("property")
        if not isinstance(rel, str) or not isinstance(n, int):
            bad.append(f"<record without file/line: {prop!r}>")
            continue
        got = line(rel, n)
        if got is None:
            bad.append(f"{rel}:{n} {prop} -> <missing file or out of range>")
        elif prop not in got:
            drifted.append(f"{rel}:{n} {prop} -> {got.strip()[:40]!r}")
    check(f"all {len(decls)} blur records carry a resolvable file:line anchor",
          not bad, "; ".join(bad[:8]))
    if drifted:
        reports.append(f"blur map: {len(drifted)}/{len(decls)} line anchors have drifted "
                       f"(the tree has moved on since the artefact was written): "
                       + "; ".join(drifted[:6]) + f"  -> {REGEN_INVENTORY}")
    else:
        oks.append(f"all {len(decls)} blur records point at a line that really declares "
                   f"their property")
    counts = blur.get("counts") or {}
    active = sum(1 for d in decls if "backdrop-filter" in str(d.get("property"))
                 and str(d.get("value", "")).strip().lower() != "none")
    none = sum(1 for d in decls if "backdrop-filter" in str(d.get("property"))
               and str(d.get("value", "")).strip().lower() == "none")
    fnblur = sum(1 for d in decls if "backdrop" not in str(d.get("property"))
                 and re.search(r"blur\s*\(", str(d.get("value", ""))))
    check("blur map: counts.total_blur_declarations == number of records",
          counts.get("total_blur_declarations") == len(decls),
          str(counts.get("total_blur_declarations")))
    check("blur map: counts.backdrop_filter_active recomputes",
          counts.get("backdrop_filter_active") == active,
          f"{counts.get('backdrop_filter_active')} vs {active}")
    check("blur map: counts.backdrop_filter_none recomputes",
          counts.get("backdrop_filter_none") == none,
          f"{counts.get('backdrop_filter_none')} vs {none}")
    check("blur map: counts.filter_with_blur_fn recomputes",
          counts.get("filter_with_blur_fn") == fnblur,
          f"{counts.get('filter_with_blur_fn')} vs {fnblur}")


def a4_nesting() -> None:
    if nest is None:
        return
    recs = records(nest, "records")
    check("nesting: schema is nedotify.backdrop-nesting.v1",
          str(nest.get("schema", "")).startswith("nedotify.backdrop-nesting"),
          str(nest.get("schema")))
    if not check(f"nesting: {len(recs)} records present", bool(recs)):
        return
    bad = []
    drifted = 0
    for d in recs:
        decl, prop, val = str(d.get("declaration", "")), d.get("property"), d.get("value")
        f, _, n = decl.partition(":")
        rel = "ui/web_new_v2/css/" + f
        got = line(rel, int(n)) if n.isdigit() else None
        # The load-bearing claim is that this declaration still exists, with this
        # value, in that file. The recorded LINE is only as fresh as the
        # dom_nesting.py run that produced the artefact, so a moved line is
        # reported as drift rather than treated as a broken record.
        present = False
        try:
            blob = text(rel)
        except OSError:
            blob = ""
        if blob:
            present = any(prop in ln and str(val) in ln for ln in blob.splitlines())
        if not present:
            bad.append(f"{decl} {prop}: {val!r} -> not found in {rel}")
            continue
        if got is None or prop not in got:
            drifted += 1
    check(f"all {len(recs)} nesting records still name a declaration that exists, "
          f"with the recorded value, in the recorded file", not bad, "; ".join(bad[:8]))
    if drifted:
        reports.append(f"backdrop_nesting.json: {drifted}/{len(recs)} records point at a "
                       f"line that no longer holds their declaration (the artefact's line "
                       f"numbers have drifted; the declarations themselves all still exist)"
                       f"  -> {REGEN_NESTING}")
    counts = nest.get("counts") or {}
    depth = max((int(d.get("nesting_depth") or 0) for d in recs), default=0)
    with_anc = sum(1 for d in recs if d.get("backdrop_filtered_ancestors"))
    check("nesting: counts.records == number of records",
          counts.get("records") == len(recs), str(counts.get("records")))
    check("nesting: counts.max_nesting_depth == the records' own maximum",
          counts.get("max_nesting_depth") == depth,
          f"{counts.get('max_nesting_depth')} vs {depth}")
    check("nesting: counts.records_with_backdro_filtered_ancestor recomputes",
          counts.get("records_with_backdro_filtered_ancestor") == with_anc,
          f"{counts.get('records_with_backdro_filtered_ancestor')} vs {with_anc}")
    check("nesting: index.html it analysed is the shipped one",
          nest.get("html") == "ui/web_new_v2/index.html", str(nest.get("html")))


